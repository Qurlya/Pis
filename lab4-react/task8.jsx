import { useState, useEffect } from 'react'

function SessionTimer() {
  const [seconds, setSeconds] = useState(0)

  useEffect(() => {
    const id = setInterval(() => {
      setSeconds((prev) => prev + 1)
    }, 1000)

    return () => clearInterval(id)
  }, [])

  return <p>Время на странице «Зоомагазин «Лапки»»: {seconds} сек</p>
}

function App() {
  const [cartCount, setCartCount] = useState(0)
  const [isLoading, setIsLoading] = useState(true)
  const [showTimer, setShowTimer] = useState(true)

  useEffect(() => {
    console.log("Витрина «Зоомагазин «Лапки»» загружена")
  }, [])

  useEffect(() => {
    console.log(
      "Корзина «Зоомагазин «Лапки»» изменилась: теперь " +
        cartCount +
        " товаров",
    )
  }, [cartCount])

  useEffect(() => {
    const id = setTimeout(() => {
      setIsLoading(false)
    }, 1500)

    return () => clearTimeout(id)
  }, [])

  if (isLoading) {
    return <p>Загрузка каталога...</p>
  }

  return (
    <div>
      <p>Товаров в корзине: {cartCount}</p>
      <button onClick={() => setCartCount(cartCount + 1)}>
        Добавить в корзину
      </button>
      <button onClick={() => setShowTimer(!showTimer)}>
        {showTimer ? "Скрыть таймер" : "Показать таймер"}
      </button>
      {showTimer && <SessionTimer />}
    </div>
  )
}

