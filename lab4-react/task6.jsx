import { useState } from 'react'

function App() {
  const products = ["Корм для кошек", "Игрушка-мышка", "Поводок"]
  const navItems = ["Каталог", "Акции", "Доставка"]
  const [catalog, setCatalog] = useState([
    { name: "Корм для кошек", price: "650 ₽" },
    { name: "Игрушка-мышка", price: "180 ₽" },
    { name: "Поводок", price: "450 ₽" },
  ])

  function handleRemove(index) {
    setCatalog(catalog.filter((_, itemIndex) => itemIndex !== index))
  }

  return (
    <div>
      <nav>
        {navItems.map((item, index) => (
          <button key={index}>{item}</button>
        ))}
      </nav>

      <ul>
        {products.map((name, index) => (
          <li key={index}>{name}</li>
        ))}
      </ul>

      <ul>
        {catalog.map((product, index) => (
          <li key={index}>
            <p>{product.name}</p>
            <p>{product.price}</p>
            <button onClick={() => handleRemove(index)}>Удалить</button>
          </li>
        ))}
      </ul>
    </div>
  )
}

