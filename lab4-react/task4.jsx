function App() {
  function handleAddClick() {
    console.log("Корм для кошек добавлен в корзину")
  }

  function removeItem(itemName) {
    console.log(itemName + " удалён из корзины")
  }

  function handleSearchChange(e) {
    console.log(e.target.value)
  }

  function handleMouseEnter() {
    console.log("наведение на Корм для кошек")
  }

  function handleMouseLeave() {
    console.log("курсор ушёл с Корм для кошек")
  }

  return (
    <div>
      <div onMouseEnter={handleMouseEnter} onMouseLeave={handleMouseLeave}>
        <p>Корм для кошек</p>
        <button onClick={handleAddClick}>Добавить в корзину</button>
        <button onClick={() => removeItem("Корм для кошек")}>Удалить</button>
      </div>
      <input
        placeholder="Поиск по каталогу «Зоомагазин «Лапки»»"
        onChange={handleSearchChange}
      />
    </div>
  )
}

