function filterPhonesByPrice(arr, threshold) {
    const filteredArray = [];
    for (let i = 0; i < arr.length; i++) {
        if (arr[i].price > threshold) {
            filteredArray.push(arr[i]);
        }
    }
    return filteredArray;
}
console.log(filterPhonesByPrice(catalog, 15000));

function createCatalogManager() {
    let operationCount = 0;

    return {
        addPhone: function(phone) {
            catalog.push(phone);
            operationCount++;
        },
        getOperationCount: function() {
            return operationCount;
        }
    };
}

const manager = createCatalogManager();
manager.addPhone({brand: 'Samsung', model: 'S23', price: 45000});
manager.addPhone({brand: 'Google', model: 'Pixel 8', price: 50000});
console.log(manager.getOperationCount());

