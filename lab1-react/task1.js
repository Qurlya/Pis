// TODO 7: Функция getType — определение реального типа
// Напишите функцию getType(value), которая принимает любое
// значение и возвращает строку с его РЕАЛЬНЫМ типом:
// - для массивов должна возвращать "array" (а не "object")
// - для null должна возвращать "null" (а не "object")
// - для остальных значений — то, что вернёт обычный typeof
// Подсказка: используйте Array.isArray() для проверки массива.

function getType(value) {
    if (value === null) {
        return "null";
    }

    if (Array.isArray(value)) {
        return "array";
    }

    return typeof value;
}

console.log(getType(13));                    // ожидаем "number"
console.log(getType("значение-3"));                  // ожидаем "string"
console.log(getType([3, 4, 5]));        // ожидаем "array"
console.log(getType(null));                            // ожидаем "null"
console.log(getType({}));                              // ожидаем "object"


